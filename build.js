import {readFile, writeFile} from 'node:fs/promises';
const model = (await readFile(new URL('./src/model.js', import.meta.url), 'utf8')).replace(/^export /gm, '');
const preferences = (await readFile(new URL('./src/preferences.js', import.meta.url), 'utf8'))
  .replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const client = await readFile(new URL('./src/client.js', import.meta.url), 'utf8');
await writeFile(new URL('./client.js', import.meta.url), `// Generated by node build.js.\nwindow.__ModuleLoader__.load({id:'dsh-sidebar',factory(require){\n${model}\n${preferences}\n${client}\n}});\n`);
